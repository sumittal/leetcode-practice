def generate_problem(
    client: LeetCodeClient,
    slug: str,
    neetcode_entry: Optional[Dict[str, Any]],
    videos: Dict[str, Any],
    force: bool,
    topinterview_slugs: Set[str],
    design_slugs: Set[str],
    companies: Optional[Dict[str, List[str]]],
) -> Optional[Path]:
    try:
        question = get_question(client, slug)
    except (HTTPError, URLError, ValueError, OSError) as error:
        print("Failed to fetch %s: %s" % (slug, error))
        return None
    if not question:
        print("Skipping %s: LeetCode returned no question data" % slug)
        return None
    try:
        problem_id = int(question["questionFrontendId"])
    except (KeyError, TypeError, ValueError):
        print("Skipping %s: missing frontend ID" % slug)
        return None
    difficulty = str(question.get("difficulty") or "").title()
    if difficulty not in DIFFICULTIES:
        print("Skipping %s: unknown difficulty" % slug)
        return None
    title = str(question.get("title") or slug)
    notes, curated_code = load_curated(slug)
    is_premium = bool(question.get("isPaidOnly"))
    premium_description = None
    if notes and isinstance(notes.get("description"), str):
        premium_description = notes["description"].strip()
    if is_premium and not premium_description:
        print("Skipping %s: paid-only problem" % slug)
        return None
    if not is_premium and not question.get("content"):
        print("Skipping %s: problem content is null" % slug)
        return None
    topics = topic_names(question)
    pattern = problem_pattern(notes, neetcode_entry, topics)
    nc = neetcode_entry or {}
    nc_pattern = str(nc.get("pattern") or "").strip()
    has_neetcode_pattern = (
        (nc.get("blind75") or nc.get("neetcode150"))
        and nc_pattern.lower() not in ("", "not specified")
    )
    topic = (
        "Design" if slug in design_slugs and not has_neetcode_pattern
        else problem_topic(pattern)
    )
    video_title, video_url, has_video = build_video(
        client, videos, neetcode_entry, problem_id, title
    )
    directory = migrate_problem_directory(problem_id, slug, difficulty, topic)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "README.md").write_text(
        render_problem_readme(
            question,
            pattern,
            study_list(slug, neetcode_entry, topinterview_slugs, design_slugs),
            video_title,
            video_url,
            has_video,
            notes,
            premium_description if is_premium else None,
            companies,
        ),
        encoding="utf-8",
    )
    write_solution(
        directory / "solution.py",
        question,
        solution_header(question, pattern, video_url, notes),
        curated_code,
        force,
    )
    return directory


def run_solutions() -> Dict[str, Tuple[str, str]]:
    statuses = {}  # type: Dict[str, Tuple[str, str]]
    solutions = [
        directory / "solution.py"
        for directory in iter_problem_directories()
        if (directory / "solution.py").is_file()
    ]
    for solution in sorted(solutions):
        status_name = solution.parent.relative_to(ROOT).as_posix()
        try:
            result = subprocess.run(
                [sys.executable, str(solution)],
                capture_output=True,
                text=True,
                timeout=10,
            )
            output = (result.stdout or "") + (result.stderr or "")
            if result.returncode != 0:
                status = "❌ Failing"
            elif "# STATUS: TODO" in solution.read_text(encoding="utf-8"):
                status = "⬜ Todo"
            else:
                status = "✅ Solved"
        except subprocess.TimeoutExpired as error:
            output = str(error)
            status = "❌ Failing"
        except OSError as error:
            output = str(error)
            status = "❌ Failing"
        statuses[status_name] = (status, output)
        print("%s %s" % (status, status_name))
        if status == "❌ Failing":
            print(output.rstrip() or "(no output)")
    return statuses


def row_metadata(directory: Path) -> Dict[str, Any]:
    parsed = parse_problem_directory(directory.name)
    if parsed is None:
        raise ValueError("Unrecognized problem directory: " + directory.name)
    problem_id, slug, directory_difficulty = parsed
    readme_path = directory / "README.md"
    readme = readme_path.read_text(encoding="utf-8") if readme_path.is_file() else ""
    title = re.match(r"#\s+\d+\.\s+(.+)", readme)
    pattern = re.search(r"^\*\*Pattern:\*\* (.+)$", readme, re.MULTILINE)
    source = re.search(r"^\*\*Study list:\*\* (.+)$", readme, re.MULTILINE)
    video = re.search(
        r"^## Video Explanation\n\n\[(.+)\]\((.+)\)$", readme, re.MULTILINE
    )
    topic = problem_topic(pattern[1].strip()) if pattern else ""
    if topic_slug(topic) != directory.parent.name:
        topic = directory.parent.name.replace("-", " ").title()
    return {
        "id": problem_id,
        "directory": directory,
        "title": title[1].strip() if title else slug.replace("-", " ").title(),
        "difficulty": directory_difficulty.title(),
        "topic": topic,
        "video_url": video[2] if video else None,
        "video_is_search": bool(video and video[1].startswith("YouTube search:")),
        "premium": bool(re.match(r"[^\n]+\n\n> 🔒", readme)),
        "study_list": source[1].strip() if source else "Other",
    }


def progress_summary(
    rows: List[Tuple[Dict[str, Any], str]],
) -> str:
    difficulties = {}
    for metadata, status in rows:
        count = difficulties.setdefault(
            metadata["difficulty"], {"total": 0, "solved": 0}
        )
        count["total"] += 1
        if status == "✅ Solved":
            count["solved"] += 1
    progress = "\n".join(
        "- %s: %d/%d solved"
        % (
            difficulty, difficulties[difficulty]["solved"], difficulties[difficulty]["total"]
        )
        for difficulty in DIFFICULTIES
        if difficulty in difficulties
    )
    return progress or "_No problems generated yet._"


def append_problem_table(
    lines: List[str],
    rows: List[Tuple[Dict[str, Any], str]],
    index_path: Path,
    show_topic: bool = False,
) -> None:
    lines.extend(
        [
            "| # | Problem | " + ("Topic | " if show_topic else "")
            + "Study list | Solution | Video guide | Status |",
            "| ---: | --- | " + ("--- | " if show_topic else "") + "--- | --- | --- | --- |",
        ]
    )
    for metadata, status in rows:
        directory = metadata["directory"]
        link = Path(os.path.relpath(directory, index_path.parent)).as_posix()
        display_title = metadata["title"] + (" 🔒" if metadata["premium"] else "")
        cells = [
            str(metadata["id"]),
            "[%s](%s/README.md)" % (display_title, link)
            if (directory / "README.md").is_file() else display_title,
        ]
        if show_topic:
            topic_index = os.path.relpath(directory.parent / "README.md", index_path.parent)
            cells.append("[%s](%s)" % (metadata["topic"], Path(topic_index).as_posix()))
        cells.extend([
            metadata["study_list"],
            "[solution](%s/solution.py)" % link
            if (directory / "solution.py").is_file() else "—",
            "[%s](%s)" % (
                "🔎 Search" if metadata["video_is_search"] else "▶ NeetCode",
                metadata["video_url"],
            ) if metadata["video_url"] else "—",
            status,
        ])
        lines.append("| " + " | ".join(cells) + " |")


def rebuild_indexes(statuses: Dict[str, Tuple[str, str]]) -> None:
    rows = []
    for directory in iter_problem_directories():
        metadata = row_metadata(directory)
        status_name = directory.relative_to(ROOT).as_posix()
        status = statuses.get(status_name, ("⬜ Todo", ""))[0]
        rows.append((metadata, status))
    rows.sort(key=lambda item: item[0]["id"])
    by_topic = {}
    by_difficulty = {difficulty: [] for difficulty in DIFFICULTIES}
    for row in rows:
        metadata, _ = row
        by_topic.setdefault(metadata["directory"].parent, []).append(row)
        by_difficulty[metadata["difficulty"]].append(row)

    difficulty_dir = ROOT / "by_difficulty"
    difficulty_dir.mkdir(exist_ok=True)
    for difficulty, difficulty_rows in by_difficulty.items():
        index_path = difficulty_dir / (difficulty.lower() + ".md")
        lines = ["# " + difficulty + " problems", "", "[All problems](../README.md)", ""]
        if difficulty_rows:
            lines.extend([progress_summary(difficulty_rows), ""])
            append_problem_table(lines, difficulty_rows, index_path, show_topic=True)
        else:
            lines.append("_No problems at this difficulty yet._")
        index_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = [
        "# LeetCode Practice",
        "",
        "A locally generated study repo with problem statements, curated approaches, and runnable Python solutions.",
        "",
        "## Browse by topic or difficulty",
        "",
        "Choose a topic from the first column or a difficulty from the header.",
        "",
        "| Topic | [Easy](by_difficulty/easy.md) | [Medium](by_difficulty/medium.md) "
        "| [Hard](by_difficulty/hard.md) | Total |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for topic_dir, topic_rows in sorted(by_topic.items()):
        topic = topic_rows[0][0]["topic"]
        topic_index = topic_dir / "README.md"
        topic_lines = [
            GENERATED_TOPIC_INDEX,
            "# " + topic,
            "",
            "[All problems](../../README.md)",
            "",
            progress_summary(topic_rows),
        ]
        counts = []
        for difficulty in DIFFICULTIES:
            matching = [row for row in topic_rows if row[0]["difficulty"] == difficulty]
            counts.append(len(matching))
            if matching:
                topic_lines.extend(["", "## " + difficulty, ""])
                append_problem_table(topic_lines, matching, topic_index)
        topic_index.write_text("\n".join(topic_lines) + "\n", encoding="utf-8")
        lines.append("| [%s](%s) | %d | %d | %d | %d |" % (
            topic, topic_index.relative_to(ROOT).as_posix(), *counts, len(topic_rows),
        ))
    lines.append("| **Total** | **%d** | **%d** | **%d** | **%d** |" % (
        *(len(by_difficulty[difficulty]) for difficulty in DIFFICULTIES), len(rows),
    ))

    for index in (ROOT / "problems").glob("*/README.md"):
        if index.parent not in by_topic and index.read_text(encoding="utf-8").startswith(
            GENERATED_TOPIC_INDEX + "\n"
        ):
            index.unlink()

    lines.extend([
        "",
        "## Overall progress",
        "",
        progress_summary(rows),
        "",
        "## Usage",
        "",
        "Problems live in `problems/<topic>/<id>-<slug>-<difficulty>/`. LeetCode Design-list",
        "problems go under Design unless they have a specific Blind 75 or NeetCode 150 pattern.",
        "Other problems use their `Pattern` (curated pattern, then NeetCode pattern, then the",
        "first LeetCode tag). Related patterns such as Array and Hash Table share a topic.",
        "Untagged problems outside the Design list use Not specified.",
        "",
        "The **Study list** column keeps the original, non-overlapping list grouping:",
        "Blind 75, the remaining NeetCode 150 problems, then additional Top Interview 150 and",
        "LeetCode Design problems. The list is not an exhaustive set of overlapping memberships.",
        "",
        "Fetch a list or selected problems to generate their files and update the indexes.",
        "Use `--index-only` to run solution self-checks and rebuild all indexes offline from local files.",
        "",
        "```sh",
        "python3 fetch_problems.py --list neetcode150",
        "python3 fetch_problems.py --list neetcode150-extra --start 0 --batch-size 25",
        "python3 fetch_problems.py --list topinterview150",
        "python3 fetch_problems.py --list topinterview150-extra --start 0 --batch-size 50",
        "python3 fetch_problems.py --list design",
        "python3 fetch_problems.py --list design-extra --start 0 --batch-size 50",
        "python3 fetch_problems.py --list blind75 --start 0 --batch-size 20",
        "python3 fetch_problems.py --slugs two-sum,valid-anagram",
        "python3 fetch_problems.py --index-only",
        "```",
        "",
        "Company tags: community-reported data from "
        "[liquidslr/leetcode-company-wise-problems]"
        "(https://github.com/liquidslr/leetcode-company-wise-problems), "
        "ranked by frequency.",
    ])
    system_design_index = ROOT / "system_design" / "README.md"
    if system_design_index.is_file():
        lines.extend(
            [
                "",
                "## System Design",
                "",
                "Read the interview-oriented "
                "[system design notes](./system_design/README.md).",
            ]
        )
    (ROOT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


